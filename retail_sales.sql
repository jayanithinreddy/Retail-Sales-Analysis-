create database sales_data ;

use sales_data ;

-- Q1 Display the first 20 records from the sales table.
select * from 
retail_sales_analyst_project
limit 20 ;

-- Q2 Find the total revenue generated from all orders.
select sum(sales) as Total_Revenue
from retail_sales_analyst_project ;

-- Q3 Find the total number of orders and unique customers.
select count(Order_ID) as Total_orders,
count(distinct Customer_ID) as Unique_Customers
from retail_sales_analyst_project ;

-- Q4 Find all unique product categories. 
select distinct Category
from retail_sales_analyst_project ;

-- Q5 Find total sales and total profit for each product category.
select Category , round(sum(sales),2) as Total_Sales,
round(sum(Profit),2) as Total_profit
from retail_sales_analyst_project
group by Category ;

-- Q6 Find total sales generated by each city. Display highest sales first.
select City , sum(sales) as Total_Sales 
from retail_sales_analyst_project
group by City 
order by Total_Sales desc
 ;
 
 -- Q7 Find the average discount for each product category.
 select Category , round(avg(Discount),2) as Avg_Discount 
 from retail_sales_analyst_project
 group by Category ;
 
 -- Q8 Find customers whose total purchase amount is greater than ₹50,000. 
 select Customer_ID, Customer_Name , sum(sales) as Total_amount
 from retail_sales_analyst_project
 group by Customer_ID, Customer_Name
 having sum(sales) > 50000 
 order by sum(sales) asc ;
 
 -- Q9 Find the top 5 products that generated the highest profit.
 select Product , round(sum(Profit),2) as Highest_Profit
 from retail_sales_analyst_project
 group by Product
 order by Highest_Profit desc 
 limit 5 ;
 
